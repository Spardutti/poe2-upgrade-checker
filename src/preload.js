'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  // popup
  onResult: (cb) => ipcRenderer.on('popup:result', (_e, r) => cb(r)),
  resize: (h) => ipcRenderer.send('popup:resize', h),
  hover: (v) => ipcRenderer.send('popup:hover', v),
  close: () => ipcRenderer.send('popup:close'),
  openSettings: () => ipcRenderer.send('open:settings'),
  openSettingsTab: (tab) => ipcRenderer.send('open:tab', tab),
  onSettingsTab: (cb) => ipcRenderer.on('settings:tab', (_e, t) => cb(t)),
  // shared
  equip: (slot, ref) => ipcRenderer.invoke('equip', slot, ref),
  setWeight: (k, v) => ipcRenderer.invoke('weights:set', k, v),
  replaceWeights: (obj) => ipcRenderer.invoke('weights:replace', obj),
  resetWeights: () => ipcRenderer.invoke('weights:reset'),
  clearSlot: (slot) => ipcRenderer.invoke('slot:clear', slot),
  setSetting: (k, v) => ipcRenderer.invoke('setting:set', k, v),
  getState: () => ipcRenderer.invoke('state:get'),
  evaluateText: (t) => ipcRenderer.invoke('evaluate:text', t),
  onChanged: (cb) => ipcRenderer.on('settings:changed', () => cb()),
  chooseGame: (game) => ipcRenderer.invoke('game:choose', game),
  onGameChanged: (cb) => ipcRenderer.on('game:changed', (_e, info) => cb(info)),
  // trade search
  tradeData: (force) => ipcRenderer.invoke('trade:data', force),
  tradeSearch: (req) => ipcRenderer.invoke('trade:search', req),
  quickFind: (target, mode, extra) => ipcRenderer.invoke('trade:quick', target, mode, extra),
  openUrl: (url) => ipcRenderer.send('open:url', url),
  recentItems: () => ipcRenderer.invoke('items:recent'),
  onItemCopied: (cb) => ipcRenderer.on('item:copied', (_e, info) => cb(info)),
  setHotkey: (accel) => ipcRenderer.invoke('hotkey:set', accel),
  openLog: () => ipcRenderer.send('open:log'),
  testPopup: () => ipcRenderer.send('popup:test'),
  getRate: (force) => ipcRenderer.invoke('rate:get', force),
  findRows: (target) => ipcRenderer.invoke('find:rows', target),
  setIgnore: (rules) => ipcRenderer.invoke('ignore:set', rules),
  statsCatalog: () => ipcRenderer.invoke('stats:catalog'),
  profiles: () => ipcRenderer.invoke('profiles:list'),
  switchProfile: (id) => ipcRenderer.invoke('profiles:switch', id),
  createProfile: (name, copy) => ipcRenderer.invoke('profiles:create', name, copy),
  renameProfile: (id, name) => ipcRenderer.invoke('profiles:rename', id, name),
  deleteProfile: (id) => ipcRenderer.invoke('profiles:delete', id),
  setResists: (r) => ipcRenderer.invoke('resists:set', r),
  importPob: (input) => ipcRenderer.invoke('pob:import', input),
  savedAlert: (id, on) => ipcRenderer.invoke('saved:alert', id, on),
  alertsStatus: () => ipcRenderer.invoke('alerts:status'),
  alertsRun: () => ipcRenderer.invoke('alerts:run'),
  accountStatus: () => ipcRenderer.invoke('account:status'),
  signIn: () => ipcRenderer.invoke('account:signin'),
  signOut: () => ipcRenderer.invoke('account:signout'),
  hideout: (id) => ipcRenderer.invoke('trade:hideout', id),
  pobStatus: (load) => ipcRenderer.invoke('pob:status', load),
  pobSheet: (refresh) => ipcRenderer.invoke('pob:sheet', refresh),
  pobEnable: (on) => ipcRenderer.invoke('pob:enable', on),
  setPriorities: (p) => ipcRenderer.invoke('priorities:set', p),
  openListing: (id) => ipcRenderer.invoke('trade:openListing', id),
  // where to spend your divines
  spendRun: (force) => ipcRenderer.invoke('spend:run', !!force),
  mapMark: (key, mark) => ipcRenderer.invoke('map:mark', key, mark),
  filterMake: () => ipcRenderer.invoke('filter:make'),
  spendGet: () => ipcRenderer.invoke('spend:get'),
  spendOpen: (slot) => ipcRenderer.invoke('spend:open', slot),
  spendAlert: (slot, minGain, maxDiv) => ipcRenderer.invoke('spend:alert', slot, minGain, maxDiv),
  onSpendProgress: (cb) => ipcRenderer.on('spend:progress', (_e, p) => cb(p)),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  updateInfo: () => ipcRenderer.invoke('update:info'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateDownload: () => ipcRenderer.invoke('update:download'),
  updateInstall: () => ipcRenderer.send('update:install'),
  onUpdateChanged: (cb) => ipcRenderer.on('update:changed', () => cb()),
  showFile: (f) => ipcRenderer.send('open:file', f),
  // results window
  onResults: (cb) => ipcRenderer.on('results:data', (_e, d) => cb(d)),
  resultsMore: () => ipcRenderer.invoke('results:more'),
  resultsRescore: () => ipcRenderer.invoke('results:rescore'),
  copyText: (t) => ipcRenderer.send('clipboard:write', t),
  hideResults: () => ipcRenderer.send('results:hide'),
  priceCheck: (target, picks) => ipcRenderer.invoke('trade:price', target, picks),
  saveSearch: (name) => ipcRenderer.invoke('saved:add', name),
  savedList: () => ipcRenderer.invoke('saved:list'),
  savedRun: (id) => ipcRenderer.invoke('saved:run', id),
  savedDelete: (id) => ipcRenderer.invoke('saved:delete', id),
  onSavedChanged: (cb) => ipcRenderer.on('saved:changed', () => cb()),
  suggestWeights: () => ipcRenderer.invoke('weights:suggest'),
  onFindUpgrade: (cb) => ipcRenderer.on('find:slot', (_e, slot) => cb(slot)),
  findUpgrade: (slot) => ipcRenderer.send('find:open', slot),
});
